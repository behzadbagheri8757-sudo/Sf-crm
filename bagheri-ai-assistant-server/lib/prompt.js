function buildMessages(history, message) {
  const msgs = [{ role: 'system', content: SYSTEM_PROMPT }];
  (history || []).forEach(function (m) { msgs.push({ role: m.role, content: m.content }); });
  msgs.push({ role: 'user', content: message });
  return msgs;
}

